import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const source = path.join(root, 'public')
const target = path.join(root, 'hosting')
const apiBase = (
  process.env.LC_API_BASE ||
  'https://bigfish-2026-d4gixfnab6e09d0f2-1253692163.ap-shanghai.app.tcloudbase.com'
).replace(/\/$/, '')

fs.rmSync(target, { recursive: true, force: true })
fs.cpSync(source, target, { recursive: true })
fs.writeFileSync(
  path.join(target, 'config.js'),
  `// generated by scripts/build-hosting.mjs\nwindow.LC_API_BASE = '${apiBase}'\n`,
  'utf8'
)

console.log(`hosting built: ${target}`)
console.log(`api base: ${apiBase}`)
